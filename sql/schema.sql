PRAGMA foreign_keys = ON;
PRAGMA journal_mode = WAL;

-- ??????????????????????????????????????????????????????????
-- DIMENSION: dim_fund
-- One row per unique AMFI scheme
-- ??????????????????????????????????????????????????????????
CREATE TABLE IF NOT EXISTS dim_fund (
    amfi_code           INTEGER     PRIMARY KEY,
    fund_house          TEXT        NOT NULL,
    scheme_name         TEXT        NOT NULL,
    category            TEXT        NOT NULL,
    sub_category        TEXT,
    plan                TEXT        NOT NULL CHECK(plan IN ('Regular','Direct')),
    launch_date         DATE,
    benchmark           TEXT,
    benchmark_key       TEXT,
    expense_ratio_pct   REAL        CHECK(expense_ratio_pct BETWEEN 0.0 AND 3.0),
    exit_load_pct       REAL,
    min_sip_amount      INTEGER,
    min_lumpsum_amount  INTEGER,
    fund_manager        TEXT,
    risk_category       TEXT,
    sebi_category_code  TEXT
);

-- ??????????????????????????????????????????????????????????
-- DIMENSION: dim_date
-- One row per calendar date — pre-populated for full range
-- ??????????????????????????????????????????????????????????
CREATE TABLE IF NOT EXISTS dim_date (
    date_id         TEXT    PRIMARY KEY,    -- 'YYYY-MM-DD'
    year            INTEGER NOT NULL,
    quarter         INTEGER NOT NULL,       -- 1-4
    month           INTEGER NOT NULL,       -- 1-12
    month_name      TEXT    NOT NULL,       -- 'January' etc.
    week_of_year    INTEGER,
    day_of_week     INTEGER,                -- 0=Monday, 6=Sunday
    is_weekend      INTEGER NOT NULL,       -- 0 or 1
    fy_year         TEXT,                   -- Indian FY e.g. 'FY2024-25'
    fy_quarter      TEXT                    -- 'Q1 FY25' etc.
);

-- ??????????????????????????????????????????????????????????
-- FACT: fact_nav
-- Daily NAV for every fund (after ffill for holidays)
-- ??????????????????????????????????????????????????????????
CREATE TABLE IF NOT EXISTS fact_nav (
    nav_id      INTEGER PRIMARY KEY AUTOINCREMENT,
    amfi_code   INTEGER NOT NULL REFERENCES dim_fund(amfi_code),
    date_id     TEXT    NOT NULL REFERENCES dim_date(date_id),
    nav         REAL    NOT NULL CHECK(nav > 0),
    UNIQUE(amfi_code, date_id)
);

CREATE INDEX IF NOT EXISTS idx_fact_nav_fund ON fact_nav(amfi_code);
CREATE INDEX IF NOT EXISTS idx_fact_nav_date ON fact_nav(date_id);

-- ??????????????????????????????????????????????????????????
-- FACT: fact_transactions
-- Investor-level buy/sell/SIP transactions
-- ??????????????????????????????????????????????????????????
CREATE TABLE IF NOT EXISTS fact_transactions (
    tx_id               INTEGER PRIMARY KEY AUTOINCREMENT,
    investor_id         TEXT    NOT NULL,
    transaction_date    TEXT    NOT NULL REFERENCES dim_date(date_id),
    amfi_code           INTEGER NOT NULL REFERENCES dim_fund(amfi_code),
    transaction_type    TEXT    NOT NULL CHECK(transaction_type IN ('SIP','Lumpsum','Redemption')),
    amount_inr          INTEGER NOT NULL CHECK(amount_inr > 0),
    state               TEXT,
    city                TEXT,
    city_tier           TEXT,
    age_group           TEXT,
    gender              TEXT,
    annual_income_lakh  REAL,
    payment_mode        TEXT,
    kyc_status          TEXT    CHECK(kyc_status IN ('Verified','Pending'))
);

CREATE INDEX IF NOT EXISTS idx_tx_fund    ON fact_transactions(amfi_code);
CREATE INDEX IF NOT EXISTS idx_tx_date    ON fact_transactions(transaction_date);
CREATE INDEX IF NOT EXISTS idx_tx_investor ON fact_transactions(investor_id);
CREATE INDEX IF NOT EXISTS idx_tx_state   ON fact_transactions(state);

-- ??????????????????????????????????????????????????????????
-- FACT: fact_performance
-- Pre-computed + validated scheme metrics
-- ??????????????????????????????????????????????????????????
CREATE TABLE IF NOT EXISTS fact_performance (
    perf_id             INTEGER PRIMARY KEY AUTOINCREMENT,
    amfi_code           INTEGER NOT NULL REFERENCES dim_fund(amfi_code),
    return_1yr_pct      REAL,
    return_3yr_pct      REAL,
    return_5yr_pct      REAL,
    benchmark_3yr_pct   REAL,
    alpha               REAL,
    beta                REAL,
    sharpe_ratio        REAL,
    sortino_ratio       REAL,
    std_dev_ann_pct     REAL,
    max_drawdown_pct    REAL,
    aum_crore           INTEGER,
    expense_ratio_pct   REAL,
    morningstar_rating  INTEGER CHECK(morningstar_rating BETWEEN 1 AND 5),
    risk_grade          TEXT,
    UNIQUE(amfi_code)
);

-- ??????????????????????????????????????????????????????????
-- FACT: fact_portfolio
-- Equity holdings per fund as of portfolio_date
-- ??????????????????????????????????????????????????????????
CREATE TABLE IF NOT EXISTS fact_portfolio (
    holding_id          INTEGER PRIMARY KEY AUTOINCREMENT,
    amfi_code           INTEGER NOT NULL REFERENCES dim_fund(amfi_code),
    stock_symbol        TEXT    NOT NULL,
    stock_name          TEXT,
    sector              TEXT,
    weight_pct          REAL    CHECK(weight_pct > 0),
    market_value_cr     REAL,
    current_price_inr   REAL,
    portfolio_date      TEXT,
    UNIQUE(amfi_code, stock_symbol)
);

CREATE INDEX IF NOT EXISTS idx_portfolio_fund   ON fact_portfolio(amfi_code);
CREATE INDEX IF NOT EXISTS idx_portfolio_sector ON fact_portfolio(sector);

-- ??????????????????????????????????????????????????????????
-- FACT: fact_aum
-- Quarterly AUM by fund house (AMC level, not fund level)
-- ??????????????????????????????????????????????????????????
CREATE TABLE IF NOT EXISTS fact_aum (
    aum_id          INTEGER PRIMARY KEY AUTOINCREMENT,
    date_id         TEXT    NOT NULL REFERENCES dim_date(date_id),
    fund_house      TEXT    NOT NULL,
    aum_lakh_crore  REAL,
    aum_crore       INTEGER CHECK(aum_crore > 0),
    num_schemes     INTEGER,
    UNIQUE(date_id, fund_house)
);

CREATE INDEX IF NOT EXISTS idx_aum_fundhouse ON fact_aum(fund_house);

-- ??????????????????????????????????????????????????????????
-- FACT: fact_sip_industry
-- Monthly industry-wide SIP metrics
-- ??????????????????????????????????????????????????????????
CREATE TABLE IF NOT EXISTS fact_sip_industry (
    sip_id                      INTEGER PRIMARY KEY AUTOINCREMENT,
    month_id                    TEXT    NOT NULL REFERENCES dim_date(date_id),
    sip_inflow_crore            INTEGER,
    active_sip_accounts_crore   REAL,
    new_sip_accounts_lakh       REAL,
    sip_aum_lakh_crore          REAL,
    yoy_growth_pct              REAL,
    UNIQUE(month_id)
);

-- ??????????????????????????????????????????????????????????
-- FACT: fact_category_inflows
-- Monthly net inflows by fund category
-- ??????????????????????????????????????????????????????????
CREATE TABLE IF NOT EXISTS fact_category_inflows (
    cat_id              INTEGER PRIMARY KEY AUTOINCREMENT,
    month_id            TEXT    NOT NULL REFERENCES dim_date(date_id),
    category            TEXT    NOT NULL,
    net_inflow_crore    REAL,
    UNIQUE(month_id, category)
);

-- ??????????????????????????????????????????????????????????
-- FACT: fact_folio_count
-- Quarterly industry folio counts
-- ??????????????????????????????????????????????????????????
CREATE TABLE IF NOT EXISTS fact_folio_count (
    folio_id                INTEGER PRIMARY KEY AUTOINCREMENT,
    month_id                TEXT    NOT NULL REFERENCES dim_date(date_id),
    total_folios_crore      REAL,
    equity_folios_crore     REAL,
    debt_folios_crore       REAL,
    hybrid_folios_crore     REAL,
    others_folios_crore     REAL,
    UNIQUE(month_id)
);

-- ??????????????????????????????????????????????????????????
-- REFERENCE: benchmark_indices
-- Daily closing values for 7 indices
-- ??????????????????????????????????????????????????????????
CREATE TABLE IF NOT EXISTS benchmark_indices (
    bench_id    INTEGER PRIMARY KEY AUTOINCREMENT,
    date_id     TEXT    NOT NULL REFERENCES dim_date(date_id),
    index_name  TEXT    NOT NULL,
    close_value REAL    CHECK(close_value > 0),
    UNIQUE(date_id, index_name)
);

CREATE INDEX IF NOT EXISTS idx_bench_index ON benchmark_indices(index_name);
CREATE INDEX IF NOT EXISTS idx_bench_date  ON benchmark_indices(date_id);
